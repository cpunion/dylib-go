package clang

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"

	"github.com/cpunion/dylib-go/abi"
)

// GoSource renders target-qualified declarations as a Go Header variable. The
// generated source uses ForHost and Session.Bind like declarations parsed at
// runtime; it adds no linkname directives or implicit library dependencies.
func (h *Header) GoSource(packageName, variableName string) ([]byte, error) {
	if h == nil || !validGoName(packageName) || !validGoName(variableName) || len(h.Functions) == 0 {
		return nil, fmt.Errorf("clang: expected declarations and valid Go package/variable names")
	}
	target, err := parseTarget(h.Target.Triple, h.Target.PointerSize)
	if err != nil || target != h.Target {
		return nil, fmt.Errorf("clang: inconsistent declaration target")
	}
	if err := h.validateDescriptions(); err != nil {
		return nil, err
	}
	var output bytes.Buffer
	fmt.Fprintf(&output, "// Code generated by compiler/clang. DO NOT EDIT.\n\npackage %s\n\nimport (\n\"github.com/cpunion/dylib-go/abi\"\nclang \"github.com/cpunion/dylib-go/compiler/clang\"\n)\n", packageName)
	fmt.Fprintf(&output, "\nvar %s = clang.Header{\nTarget: clang.Target{Triple: %q, OS: %q, Arch: %q, PointerSize: %d},\nFunctions: []clang.Declaration{\n", variableName, target.Triple, target.OS, target.Arch, target.PointerSize)
	seen := make(map[string]bool)
	for _, function := range h.Functions {
		if !cIdentifier(function.Name) || function.Symbol == "" || seen[function.Name] {
			return nil, fmt.Errorf("clang: invalid or duplicate declaration %q", function.Name)
		}
		seen[function.Name] = true
		fmt.Fprintf(&output, "{Name:%q,Symbol:%q,Signature:", function.Name, function.Symbol)
		writeSignature(&output, function.Signature)
		if len(function.FunctionPointers) != 0 {
			fmt.Fprint(&output, ",FunctionPointers:")
			writeFunctionPointers(&output, function.FunctionPointers)
		}
		fmt.Fprint(&output, "},\n")
	}
	fmt.Fprint(&output, "},\n")
	if len(h.Records) != 0 {
		fmt.Fprint(&output, "Records:[]clang.Record{\n")
		for _, record := range h.Records {
			if err := validRecordLayout(record); err != nil {
				return nil, err
			}
			fmt.Fprintf(&output, "{Name:%q,Description:", record.Name)
			writeDescription(&output, record.Description)
			fmt.Fprintf(&output, ",Layout:abi.Layout{Size:%d,Alignment:%d,Offsets:[]uint64{", record.Layout.Size, record.Layout.Alignment)
			for _, offset := range record.Layout.Offsets {
				fmt.Fprintf(&output, "%d,", offset)
			}
			fmt.Fprint(&output, "}}")
			if len(record.TypedefAlignments) != 0 {
				fmt.Fprint(&output, ",TypedefAlignments:[]clang.RecordTypedefAlignment{")
				for _, alias := range record.TypedefAlignments {
					fmt.Fprintf(&output, "{Name:%q,Aligned:%d},", alias.Name, alias.Aligned)
				}
				fmt.Fprint(&output, "}")
			}
			if record.Packed {
				fmt.Fprint(&output, ",Packed:true")
			}
			if len(record.PackedFields) != 0 {
				fmt.Fprint(&output, ",PackedFields:[]int{")
				for _, position := range record.PackedFields {
					fmt.Fprintf(&output, "%d,", position)
				}
				fmt.Fprint(&output, "}")
			}
			if record.MaxFieldAlignment != 0 {
				fmt.Fprintf(&output, ",MaxFieldAlignment:%d", record.MaxFieldAlignment)
			}
			if len(record.MemberAlignments) != 0 {
				fmt.Fprint(&output, ",MemberAlignments:[]uint64{")
				for _, alignment := range record.MemberAlignments {
					fmt.Fprintf(&output, "%d,", alignment)
				}
				fmt.Fprint(&output, "}")
			}
			if record.Aligned != 0 {
				fmt.Fprintf(&output, ",Aligned:%d", record.Aligned)
			}
			if record.IndirectArgument {
				fmt.Fprint(&output, ",IndirectArgument:true")
			}
			if record.IndirectResult {
				fmt.Fprint(&output, ",IndirectResult:true")
			}
			if record.ArgumentAlignment != 0 {
				fmt.Fprintf(&output, ",ArgumentAlignment:%d", record.ArgumentAlignment)
			}
			if len(record.FieldAlignments) != 0 {
				fmt.Fprint(&output, ",FieldAlignments:[]clang.FieldAlignment{")
				for _, field := range record.FieldAlignments {
					fmt.Fprintf(&output, "{Position:%d,Aligned:%d},", field.Position, field.Aligned)
				}
				fmt.Fprint(&output, "}")
			}
			if len(record.FieldTypeAlignments) != 0 {
				fmt.Fprint(&output, ",FieldTypeAlignments:[]clang.TypedefFieldAlignment{")
				for _, field := range record.FieldTypeAlignments {
					fmt.Fprintf(&output, "{Position:%d", field.Position)
					if field.ArrayDepth != 0 {
						fmt.Fprintf(&output, ",ArrayDepth:%d", field.ArrayDepth)
					}
					fmt.Fprintf(&output, ",Aligned:%d,StorageAlignment:%d},", field.Aligned, field.StorageAlignment)
				}
				fmt.Fprint(&output, "}")
			}
			if len(record.Bitfields) != 0 {
				fmt.Fprint(&output, ",Bitfields:[]clang.Bitfield{")
				for _, field := range record.Bitfields {
					fmt.Fprintf(&output, "{Position:%d,Width:%d", field.Position, field.Width)
					if field.TypeAlignment != 0 {
						fmt.Fprintf(&output, ",TypeAlignment:%d,StorageAlignment:%d", field.TypeAlignment, field.StorageAlignment)
					}
					fmt.Fprint(&output, ",Mask:[]byte{")
					for _, b := range field.Mask {
						fmt.Fprintf(&output, "%d,", b)
					}
					fmt.Fprint(&output, "}},")
				}
				fmt.Fprint(&output, "}")
			}
			if len(record.Padding) != 0 {
				fmt.Fprint(&output, ",Padding:[]clang.BitfieldPadding{")
				for _, field := range record.Padding {
					fmt.Fprintf(&output, "{Before:%d,Type:abi.Type(%d),Width:%d,Offset:%d", field.Before, field.Type, field.Width, field.Offset)
					if field.Packed {
						fmt.Fprint(&output, ",Packed:true")
					}
					if field.Aligned != 0 {
						fmt.Fprintf(&output, ",Aligned:%d", field.Aligned)
					}
					if field.TypeAlignment != 0 {
						fmt.Fprintf(&output, ",TypeAlignment:%d", field.TypeAlignment)
					}
					if field.StorageAlignment != 0 {
						fmt.Fprintf(&output, ",StorageAlignment:%d", field.StorageAlignment)
					}
					if field.Gap != 0 {
						fmt.Fprintf(&output, ",Gap:%d", field.Gap)
					}
					if len(field.Mask) != 0 {
						fmt.Fprint(&output, ",Mask:[]byte{")
						for _, b := range field.Mask {
							fmt.Fprintf(&output, "%d,", b)
						}
						fmt.Fprint(&output, "}")
					}
					fmt.Fprint(&output, "},")
				}
				fmt.Fprint(&output, "}")
			}
			if len(record.FunctionPointers) != 0 {
				fmt.Fprint(&output, ",FunctionPointers:")
				writeFunctionPointers(&output, record.FunctionPointers)
			}
			fmt.Fprint(&output, "},\n")
		}
		fmt.Fprint(&output, "},\n")
	}
	fmt.Fprint(&output, "}\n")
	return format.Source(output.Bytes())
}

func writeFunctionPointers(output *bytes.Buffer, pointers []FunctionPointer) {
	fmt.Fprint(output, "[]clang.FunctionPointer{")
	for _, pointer := range pointers {
		fmt.Fprintf(output, "{Position:%d,Signature:", pointer.Position)
		writeSignature(output, pointer.Signature)
		if pointer.Indirection != 0 {
			fmt.Fprintf(output, ",Indirection:%d", pointer.Indirection)
		}
		if len(pointer.FunctionPointers) != 0 {
			fmt.Fprint(output, ",FunctionPointers:")
			writeFunctionPointers(output, pointer.FunctionPointers)
		}
		fmt.Fprint(output, "},")
	}
	fmt.Fprint(output, "}")
}

func writeSignature(output *bytes.Buffer, signature abi.Signature) {
	fmt.Fprintf(output, "abi.Signature{Result:abi.%s, Convention:abi.%s, Variadic:%t, FixedArgs:%d, Args:[]abi.Type{", typeName(signature.Result), conventionName(signature.Convention), signature.Variadic, signature.FixedArgs)
	for _, parameter := range signature.Args {
		fmt.Fprintf(output, "abi.%s,", typeName(parameter))
	}
	fmt.Fprint(output, "}")
	if len(signature.ArgTypes) != 0 {
		fmt.Fprint(output, ",ArgTypes:[]abi.TypeDesc{")
		for _, description := range signature.ArgTypes {
			writeDescription(output, description)
			fmt.Fprint(output, ",")
		}
		fmt.Fprint(output, "}")
	}
	if signature.ResultType != nil {
		fmt.Fprint(output, ",ResultType:&")
		writeDescription(output, *signature.ResultType)
	}
	fmt.Fprint(output, "}")
}

func writeDescription(output *bytes.Buffer, description abi.TypeDesc) {
	fmt.Fprintf(output, "abi.TypeDesc{Type:abi.%s", typeName(description.Type))
	if description.Len != 0 {
		fmt.Fprintf(output, ",Len:%d", description.Len)
	}
	if description.Elem != nil {
		fmt.Fprint(output, ",Elem:&")
		writeDescription(output, *description.Elem)
	}
	if len(description.Fields) != 0 {
		fmt.Fprint(output, ",Fields:[]abi.Field{")
		for _, field := range description.Fields {
			fmt.Fprintf(output, "{Name:%q,Type:", field.Name)
			writeDescription(output, field.Type)
			fmt.Fprint(output, "},")
		}
		fmt.Fprint(output, "}")
	}
	fmt.Fprint(output, "}")
}

func typeName(id abi.Type) string {
	return map[abi.Type]string{abi.Void: "Void", abi.I8: "I8", abi.U8: "U8", abi.I16: "I16", abi.U16: "U16", abi.I32: "I32", abi.U32: "U32", abi.I64: "I64", abi.U64: "U64", abi.F32: "F32", abi.F64: "F64", abi.Bool: "Bool", abi.Pointer: "Pointer", abi.Struct: "Struct", abi.Array: "Array"}[id]
}

func conventionName(id abi.Convention) string {
	return map[abi.Convention]string{abi.Default: "Default", abi.CDecl: "CDecl", abi.StdCall: "StdCall", abi.FastCall: "FastCall", abi.VectorCall: "VectorCall"}[id]
}

func validGoName(name string) bool {
	return name != "_" && token.IsIdentifier(name) && !token.Lookup(name).IsKeyword()
}
